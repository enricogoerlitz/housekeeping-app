// Resets the app data of a Supabase project before the new migration base (spec 0028, REQ-005,
// REQ-006, decisions 3 and 4; runbook "Erste produktive Version (0028)" in
// docs/architecture/betrieb.md). Deletes the schemas' objects of the app (`public`, `private`),
// the pg_cron jobs, the migration history and the photos. Accounts (`auth`), the Vault, the auth
// settings and the function secrets stay.
//
// Only by hand, from a terminal, never in CI (conventions.mjs, spec 0031, AC-019):
//
//   node scripts/reset-app-data.mjs --project <project-ref>
//
// Every command names the project explicitly (`--remote=<ref>`), nothing relies on `supabase
// link`; a linked project other than the one named stops it. Before anything is deleted the
// project's name must be typed. No secret is taken as an argument or printed.
import { spawnSync } from 'node:child_process';
import { chmodSync, existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { createInterface } from 'node:readline/promises';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REF = /^[a-z]{20}$/;
const BUCKET = 'household-media';

/** `{ project }` from the arguments; throws with the reason. */
export function parseArgs(argv) {
  let project;
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === '--project') {
      project = argv[index + 1];
      index += 1;
    } else {
      throw new Error(`Unbekannte Angabe ${argv[index]}`);
    }
  }
  if (project === undefined) throw new Error('--project <Projektkennung> fehlt');
  if (!REF.test(project)) throw new Error(`„${project}“ ist keine Projektkennung (20 Buchstaben)`);
  return { project };
}

/** Never in CI, never without a person at a terminal (security check 0031). */
export function checkEnvironment({ env, interactive }) {
  if (env.CI || env.GITHUB_ACTIONS) {
    throw new Error('reset-app-data.mjs läuft nur von Hand, nie in CI');
  }
  if (!interactive) throw new Error('reset-app-data.mjs braucht ein Terminal für die Rückfrage');
}

/** A project linked with `supabase link` must be the one named (AC-015). */
export function checkLinked(dir, project) {
  const file = path.join(dir, 'supabase/.temp/project-ref');
  if (!existsSync(file)) return;
  const linked = readFileSync(file, 'utf8').trim();
  if (linked && linked !== project) {
    throw new Error(`Genannt ist ${project}, verlinkt ist ${linked}: abgebrochen, nichts geändert`);
  }
}

/**
 * One statement, so one transaction (`supabase db query` takes a single statement): the jobs, the
 * app's objects in `private` and `public`, the migration history.
 */
export function resetSql() {
  return `-- Generated by scripts/reset-app-data.mjs (spec 0028). Never committed.
do $reset$
declare
  item record;
begin
  perform cron.unschedule(jobid) from cron.job;
  drop schema if exists private cascade;
  for item in
    select format('drop table if exists public.%I cascade', tablename) as statement
    from pg_catalog.pg_tables where schemaname = 'public'
  loop
    execute item.statement;
  end loop;
  for item in
    select format('drop view if exists public.%I cascade', viewname) as statement
    from pg_catalog.pg_views where schemaname = 'public'
  loop
    execute item.statement;
  end loop;
  -- Functions and types of the app; those of extensions stay.
  for item in
    select format('drop routine if exists %s cascade', p.oid::regprocedure) as statement
    from pg_catalog.pg_proc p
    where p.pronamespace = 'public'::regnamespace
      and not exists (
        select 1 from pg_catalog.pg_depend d
        where d.classid = 'pg_catalog.pg_proc'::regclass and d.objid = p.oid and d.deptype = 'e'
      )
  loop
    execute item.statement;
  end loop;
  for item in
    select format('drop type if exists public.%I cascade', t.typname) as statement
    from pg_catalog.pg_type t
    where t.typnamespace = 'public'::regnamespace
      and t.typtype in ('e', 'd')
      and not exists (
        select 1 from pg_catalog.pg_depend d
        where d.classid = 'pg_catalog.pg_type'::regclass and d.objid = t.oid and d.deptype = 'e'
      )
  loop
    execute item.statement;
  end loop;
  delete from supabase_migrations.schema_migrations;
end
$reset$;
`;
}

function supabase(args, options = {}) {
  const result = spawnSync('pnpm', ['exec', 'supabase', ...args], {
    cwd: root,
    encoding: 'utf8',
    ...options,
  });
  if (result.status !== 0) {
    throw new Error(`supabase ${args[0]} ${args[1] ?? ''} ist fehlgeschlagen (${result.status})`);
  }
  return result.stdout;
}

function projectName(project) {
  const projects = JSON.parse(supabase(['projects', 'list', '--output-format', 'json']));
  const found = (Array.isArray(projects) ? projects : []).find(
    (entry) => entry?.id === project || entry?.ref === project,
  );
  if (!found?.name) throw new Error(`Projekt ${project} ist mit diesem Login nicht sichtbar`);
  return found.name;
}

async function main(argv) {
  checkEnvironment({ env: process.env, interactive: Boolean(process.stdin.isTTY) });
  const { project } = parseArgs(argv);
  checkLinked(root, project);
  const name = projectName(project);
  const prompt = createInterface({ input: process.stdin, output: process.stdout });
  const typed = await prompt.question(
    `Alle App-Daten, Aufträge, die Migrationshistorie und die Fotos von „${name}“ (${project}) ` +
      `werden gelöscht. Zum Bestätigen den Projektnamen eintippen: `,
  );
  prompt.close();
  if (typed.trim() !== name) {
    console.error('Name stimmt nicht: abgebrochen, nichts geändert.');
    return 1;
  }

  const folder = mkdtempSync(path.join(tmpdir(), 'reset-app-data-'));
  chmodSync(folder, 0o700);
  const file = path.join(folder, 'reset.sql');
  try {
    writeFileSync(file, resetSql(), { mode: 0o600 });
    supabase(['db', 'query', `--remote=${project}`, '--file', file], { stdio: 'inherit' });
  } finally {
    rmSync(folder, { recursive: true, force: true });
  }
  supabase(['storage', 'rm', `--remote=${project}`, '--recursive', `ss:///${BUCKET}`], {
    stdio: 'inherit',
  });
  console.log(`Zurückgesetzt: ${name} (${project}). Als Nächstes die neue Basis einspielen.`);
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).then(
    (code) => process.exit(code),
    (error) => {
      console.error(`FEHLER: ${error.message}`);
      process.exit(1);
    },
  );
}
