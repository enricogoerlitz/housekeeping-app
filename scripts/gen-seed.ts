// Writes the local seed (supabase/seed.sql) and the seed ids for e2e (e2e/seed-ids.ts) from the
// demo households (packages/api/src/seed). The output does not depend on the day it runs:
// dates and times are relative to the `supabase db reset` that loads the seed.
//
//   pnpm db:seed:gen
import { spawnSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { generateSeed } from '../packages/api/src/seed/seed-sql';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

async function main(): Promise<void> {
  // Any base day gives the same output (pinned by seed-sql.test.ts).
  const seed = await generateSeed(new Date().toISOString().slice(0, 10));

  writeFileSync(resolve(root, 'supabase/seed.sql'), seed.sql);

  const entries = (ids: Record<string, string>) =>
    Object.entries(ids)
      .map(([slug, id]) => `  '${slug}': '${id}',`)
      .join('\n');
  const idsFile = `// Generated by \`pnpm db:seed:gen\` (scripts/gen-seed.ts) — do not edit.
  // UUIDs of the local seed (supabase/seed.sql) by the demo's readable slug ids.

  /** Households, the test accounts' profiles, and the top-level entities of "Enrico & Nadja". */
  export const seedIds = {
  ${entries(seed.e2eIds)}
  } as const;

  /** Top-level entities of the household "Test" (same slugs, other ids). */
  export const testSeedIds = {
  ${entries(seed.e2eTestIds)}
  } as const;
  `;
  const idsPath = resolve(root, 'e2e/seed-ids.ts');
  writeFileSync(idsPath, idsFile);
  const prettier = spawnSync(resolve(root, 'node_modules/.bin/prettier'), ['--write', idsPath], {
    stdio: 'ignore',
  });
  if (prettier.status !== 0) throw new Error('prettier failed on e2e/seed-ids.ts');

  console.log('Wrote supabase/seed.sql and e2e/seed-ids.ts');
}

main().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});
