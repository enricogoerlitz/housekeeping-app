// Invitations of the preview (spec 0014, Task 7; AC-014, AC-015, plan decision 7). After the
// reset and the preview seed, the job "Supabase Vorschau" of .github/workflows/preview.yml invites
// the Google addresses of the secret PREVIEW_INVITE_EMAILS (comma separated) into the demo household
// "Enrico & Nadja". Only invited addresses can sign up (private.before_user_created_hook).
//
//   PREVIEW_INVITE_EMAILS=… SUPABASE_PROJECT_REF=… SUPABASE_ACCESS_TOKEN=… node scripts/preview-invites.mjs
//
// No dependencies: the job has an environment and installs no packages. The addresses are checked
// with the rule of private.is_valid_email, never printed (also not in an error message), carried
// hex-encoded in the SQL, and the SQL lives in a private temp file (0600 in a 0700 folder under
// $RUNNER_TEMP) only while `supabase db query --remote` runs; the output of the query is dropped.
import { spawnSync } from 'node:child_process';
import { chmodSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const HOUSEHOLD_NAME = 'Enrico & Nadja';
/** Same rule as private.is_valid_email on the server (after trimming and lowercasing). */
const EMAIL = /^[^@\s]+@[^@\s.]+(\.[^@\s.]+)+$/;
const isValid = (email) => email.length <= 254 && EMAIL.test(email);
const PROJECT_REF = /^[a-z]{20}$/;

/** The checked, lowercased addresses, each once; the error names positions, never values. */
export function parseInviteEmails(raw) {
  const emails = (raw ?? '')
    .split(',')
    .map((part) => part.trim().toLowerCase())
    .filter(Boolean);
  if (emails.length === 0) throw new Error('PREVIEW_INVITE_EMAILS ist leer oder nicht gesetzt');
  const invalid = emails.flatMap((email, index) => (isValid(email) ? [] : [index + 1]));
  if (invalid.length > 0) {
    throw new Error(
      `PREVIEW_INVITE_EMAILS: Adresse ${invalid.join(', ')} ist ungültig (erwartet name@domain.tld, höchstens 254 Zeichen)`,
    );
  }
  return [...new Set(emails)];
}

/** One block: fails unless exactly one household "Enrico & Nadja" exists, then invites. */
export function invitesSql(emails) {
  if (
    emails.length === 0 ||
    emails.some((email) => email !== email.trim().toLowerCase() || !isValid(email))
  ) {
    throw new Error('invitesSql: die Adressen zuerst mit parseInviteEmails prüfen');
  }
  const values = emails.map((email) => `'${Buffer.from(email, 'utf8').toString('hex')}'`);
  const name = HOUSEHOLD_NAME.replaceAll("'", "''");
  return `-- Generated by scripts/preview-invites.mjs (spec 0014, AC-014). Never committed.
do $$
declare
  v_household uuid;
begin
  select id into strict v_household from public.households where name = '${name}';
  insert into public.household_invitations (household_id, email)
  select v_household, convert_from(decode(value, 'hex'), 'UTF8')
  from unnest(array[${values.join(', ')}]) as value
  on conflict (household_id, email) do nothing;
end
$$;
`;
}

/**
 * Writes the SQL into a private temp file, hands the CLI arguments to runQuery and deletes the
 * file again, whatever happens. Resolves to the exit status of runQuery.
 */
export async function runInvites({ emails, ref, runQuery, tmpRoot = tmpdir() }) {
  if (!PROJECT_REF.test(ref ?? '')) {
    throw new Error('SUPABASE_PROJECT_REF fehlt oder ist keine Projekt-Ref (20 Kleinbuchstaben)');
  }
  const sql = invitesSql(emails);
  const dir = mkdtempSync(path.join(tmpRoot, 'preview-invites-'));
  try {
    chmodSync(dir, 0o700);
    const file = path.join(dir, 'invites.sql');
    writeFileSync(file, sql, { mode: 0o600, flag: 'wx' });
    chmodSync(file, 0o600);
    return await runQuery(['db', 'query', `--remote=${ref}`, '--yes', '--file', file], file);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

/** The Supabase CLI with its output dropped: an error of the database could quote a value. */
function supabase(args) {
  const result = spawnSync('supabase', args, { stdio: ['ignore', 'ignore', 'ignore'] });
  if (result.error) throw new Error(`supabase-CLI nicht ausführbar (${result.error.code})`);
  return result.status ?? 1;
}

function fail(message) {
  if (process.env.GITHUB_ACTIONS === 'true') console.log(`::error::${message}`);
  else console.error(`FEHLER: ${message}`);
  return 1;
}

async function main() {
  try {
    const emails = parseInviteEmails(process.env.PREVIEW_INVITE_EMAILS);
    const status = await runInvites({
      emails,
      ref: process.env.SUPABASE_PROJECT_REF?.trim(),
      runQuery: supabase,
      tmpRoot: process.env.RUNNER_TEMP || tmpdir(),
    });
    if (status !== 0) {
      return fail(
        `Einladungen der Vorschau gescheitert (supabase db query, Exit ${status}; Haushalt „${HOUSEHOLD_NAME}“ fehlt oder ist doppelt?)`,
      );
    }
    console.log(`Vorschau: ${emails.length} Einladung(en) in „${HOUSEHOLD_NAME}“ angelegt.`);
    return 0;
  } catch (error) {
    return fail(error.message);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = await main();
}
