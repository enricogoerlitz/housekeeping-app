-- Spec 0042 "Orte, Einfügen, Teilen und Eigentümer des Haushalts".
--
-- REQ-002: a store (Markt) has a map link (maps_url), opened by "Route" like the one of a
-- restaurant; members read it like the rest of the store (RLS of stores) and write it through
-- apply_changes. Additive: a nullable column, no backfill.
--
-- REQ-005 (Decision 1): the owner (Eigentümer) of a household is derived, not stored: the member
-- with the earliest household_members.created_at, on a tie the smaller profile id. Only the owner
-- invites (invite_member) and removes others (remove_member); every member can still leave. When
-- the owner leaves or deletes her account (profiles → household_members on delete cascade), the
-- next oldest member is the owner without any write. created_at of a membership is set by
-- set_timestamps on insert and kept on every update; members can neither insert nor update
-- household_members (no grant), so nobody can move herself to the front.

-- ---------------------------------------------------------------------------------------------
-- stores.maps_url (REQ-002)
-- ---------------------------------------------------------------------------------------------

-- Opened by the app ("Route"), so only http(s) links are stored, like restaurants.maps_url.
alter table public.stores
  add column maps_url text
    constraint stores_maps_url_valid check (char_length(maps_url) <= 2000 and maps_url ~* '^https?://');

grant insert (maps_url) on public.stores to authenticated;
grant update (maps_url) on public.stores to authenticated;

-- ---------------------------------------------------------------------------------------------
-- Owner (REQ-005)
-- ---------------------------------------------------------------------------------------------

-- The owner of a household: earliest join, ties by the smaller profile id; null without members.
-- Called only from the security definer functions below, so it has no grant.
create function private.household_owner(p_household_id uuid)
returns uuid
language sql
stable
set search_path = ''
as $$
  select m.profile_id
  from public.household_members m
  where m.household_id = p_household_id
  order by m.created_at, m.profile_id
  limit 1
$$;

revoke execute on function private.household_owner(uuid) from public, anon, authenticated;

-- Invites an address into a household the caller owns (AC-013). Inviting the same address again
-- returns the open invitation. Unchanged from 20261122181410 except the owner check.
create or replace function private.invite_member(p_household_id uuid, p_email text)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_email text := lower(btrim(p_email));
  v_invitation_id uuid;
begin
  if v_uid is null then
    raise exception 'not_authenticated' using errcode = '42501';
  end if;

  -- Locked like remove_member does, so an owner who is just leaving cannot invite at the same
  -- time as the next owner.
  perform 1 from public.households h where h.id = p_household_id for update;

  if not exists (
    select 1 from public.household_members m
    where m.household_id = p_household_id and m.profile_id = v_uid
  ) then
    raise exception 'not_member' using errcode = '42501';
  end if;
  if private.household_owner(p_household_id) is distinct from v_uid then
    raise exception 'not_owner' using errcode = '42501';
  end if;
  if not private.is_valid_email(v_email) then
    raise exception 'invalid_email' using errcode = '22023';
  end if;
  if exists (
    select 1 from public.household_members m
    join public.profiles p on p.id = m.profile_id
    where m.household_id = p_household_id and p.email = v_email
  ) then
    raise exception 'already_member' using errcode = '23505';
  end if;

  insert into public.household_invitations (household_id, email, invited_by)
  values (p_household_id, v_email, v_uid)
  on conflict (household_id, email) do update set invited_by = excluded.invited_by
  returning id into v_invitation_id;

  return v_invitation_id;
end
$$;

-- The owner removes another member (AC-012); every member leaves herself (AC-014). The last
-- member cannot leave. The household row is locked first, so a leaving owner and a removal by the
-- next owner happen one after the other. Unchanged from 20261121062344 except the owner check.
create or replace function private.remove_member(p_household_id uuid, p_profile_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
begin
  if v_uid is null then
    raise exception 'not_authenticated' using errcode = '42501';
  end if;

  perform 1 from public.households h where h.id = p_household_id for update;

  if not exists (
    select 1 from public.household_members m
    where m.household_id = p_household_id and m.profile_id = v_uid
  ) then
    raise exception 'not_member' using errcode = '42501';
  end if;
  if p_profile_id is distinct from v_uid
     and private.household_owner(p_household_id) is distinct from v_uid then
    raise exception 'not_owner' using errcode = '42501';
  end if;
  if not exists (
    select 1 from public.household_members m
    where m.household_id = p_household_id and m.profile_id = p_profile_id
  ) then
    raise exception 'member_not_found' using errcode = 'P0002';
  end if;
  if (select count(*) from public.household_members m where m.household_id = p_household_id) <= 1 then
    raise exception 'last_member' using errcode = 'P0001';
  end if;

  delete from public.household_members m
  where m.household_id = p_household_id and m.profile_id = p_profile_id;
end
$$;

-- ---------------------------------------------------------------------------------------------
-- apply_changes: stores.maps_url (REQ-002). Unchanged from 20261123070918 except the stores rule.
